import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = fileURLToPath(new URL('../', import.meta.url));
const output = path.join(root, 'pkg/ragjs/assets/rag.js');
const result = await build({
  absWorkingDir: root,
  entryPoints: ['pkg/ragjs/src/api/index.js'],
  bundle: true,
  write: false,
  format: 'iife',
  globalName: '__ragModule',
  platform: 'neutral',
  target: 'es2020',
  keepNames: true,
  charset: 'utf8',
  banner: { js: '// Generated by pnpm build from pkg/ragjs/src. DO NOT EDIT.\n(function () {' },
  footer: {
    js: "if (typeof module === 'object' && module.exports) module.exports = __ragModule.rag;\nelse globalThis.rag = __ragModule.rag;\n})();",
  },
});
const generated = result.outputFiles[0].contents;
if (process.argv.includes('--check')) {
  const current = await readFile(output);
  if (!current.equals(generated)) {
    console.error('Generated rag.js is stale. Run pnpm build and commit the result.');
    process.exitCode = 1;
  } else console.log('Generated rag.js is current.');
} else {
  await writeFile(output, generated);
  console.log('Generated pkg/ragjs/assets/rag.js');
}
